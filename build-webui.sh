#!/usr/bin/env bash
# Fetch the shared web UI and generate Sources/a11y/Assets.swift.
#
# The UI lives in exactly ONE place (easydev-org/easystream-webui). Swift has no
# `include_str!`, and the daemon is boot-fetched as a SINGLE executable (a
# SwiftPM resource bundle would not travel), so the UI is inlined as string
# literals in a GENERATED Swift file.
set -Eeuo pipefail
cd "$(dirname "$0")"

REF="${WEBUI_REF:-main}"
PROXY="${HTTPS_PROXY:-${HTTP_PROXY:-}}"
URL="https://codeload.github.com/easydev-org/easystream-webui/tar.gz/refs/heads/${REF}"
DEST="Sources/a11y/Resources/webui"
OUT="Sources/a11y/Assets.swift"

tmp="$(mktemp -d)"; trap 'rm -rf "${tmp}"' EXIT
curl -fsSL ${PROXY:+-x "${PROXY}"} -o "${tmp}/webui.tgz" "${URL}"
tar xzf "${tmp}/webui.tgz" -C "${tmp}"
rm -rf "${DEST}"; mkdir -p "${DEST}"
cp "${tmp}"/easystream-webui-*/webui/app.js     "${DEST}/app.js"
cp "${tmp}"/easystream-webui-*/webui/index.html "${DEST}/index.html"

# Escape for a Swift multi-line string literal: backslash first, then """.
esc() { sed -e 's/\\/\\\\/g' -e 's/"""/\\"\\"\\"/g' "$1"; }
{
  echo "import Foundation"
  echo
  echo "/// Assets holds the embedded web UI as INLINE string literals."
  echo "///"
  echo "/// GENERATED by build-webui.sh from easydev-org/easystream-webui — do not"
  echo "/// edit. Inlined because the daemon is boot-fetched as a SINGLE executable"
  echo "/// (a SwiftPM Bundle.module resource would not travel with it)."
  echo "enum Assets {"
  echo '    static let index: String = """'
  esc "${DEST}/index.html"
  echo '"""'
  echo '    static let js: String = """'
  esc "${DEST}/app.js"
  echo '"""'
  echo "}"
} > "${OUT}"
echo "webui ${REF} -> ${OUT} ($(wc -c <"${OUT}") bytes)"
